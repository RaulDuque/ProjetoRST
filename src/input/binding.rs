impl PhysicalMouse {
    pub fn label(self) -> &'static str {
        match self {
            PhysicalMouse::Left => "Mouse left",
            PhysicalMouse::Right => "Mouse right",
            PhysicalMouse::Middle => "Mouse middle",
        }
    }

    pub fn to_button(self) -> MouseButton {
        match self {
            PhysicalMouse::Left => MouseButton::Left,
            PhysicalMouse::Right => MouseButton::Right,
            PhysicalMouse::Middle => MouseButton::Middle,
        }
    }

    pub fn from_button(button: MouseButton) -> Option<Self> {
        match button {
            MouseButton::Left => Some(PhysicalMouse::Left),
            MouseButton::Right => Some(PhysicalMouse::Right),
            MouseButton::Middle => Some(PhysicalMouse::Middle),
            _ => None,
        }
    }
}

impl Binding {
    pub fn label(self) -> &'static str {
        match self {
            Binding::Key(key) => key.label(),
            Binding::Mouse(button) => button.label(),
        }
    }
}
