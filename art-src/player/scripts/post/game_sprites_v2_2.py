"""Staging of the V2.2 weaponless candidate: body atlases without the sabre,
plus the per-frame equipment sockets.

Reads the masters and sockets of ``bpy/build_game_sprites_v2_2.py``
(``renders/v2_2_weaponless/<v1_3|v1_4|v1_5>/game_sprites_manifest.json``,
whose clip metadata are copied from the V1.3-V1.5 builds) and writes a
staging directory laid out like ``assets/`` (default
``renders/v2_2_weaponless/stage/``):

- ``sprites/player/player_locomotion.png`` and ``player_combat.png``: the
  published V1.5 layout (same clips, order, indices, durations and pivots;
  hurt = hurt_a, fall = fall_v15), rendered without the sabre;
- ``sprites/player/player_effects.png``: the V1.5 effects (unchanged);
- ``animations/player.ron``: the V1.5 manifest plus ``weapon_in_body: false``;
- ``animations/player_sockets.ron``: hands, head, chest and back per frame;
- ``publish.json`` (generator 2.2).

It never writes ``assets/``: ``publish_guard.py check --stage ...`` validates
the candidate and ``publish`` replaces the published files (with backup and
rollback), only with the owner's authorisation. Comparison sheets (published
vs candidate, with the sockets drawn) go to ``comparisons/v2_2_weaponless/``.

Usage:
    python3 art-src/player/scripts/post/game_sprites_v2_2.py [--stage DIR] [--sheet-dir DIR]
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

from PIL import Image, ImageDraw

import game_sprites_v1_3 as G3  # V1.3 packing and checks, unchanged
import game_sprites_v1_4 as G4  # V1.4 merge and durations, unchanged
import game_sprites_v1_5 as G5  # V1.5 effects and RON writer, unchanged
import vfx_v1_5 as VFX
from contract import HD_DENSITY
from labels import font
from publish_guard import ASSETS, SOCKETS, STAGE_INFO, refuse_protected_output

PLAYER_DIR = Path(__file__).resolve().parents[2]
RUN = PLAYER_DIR / "renders" / "v2_2_weaponless"
SHEETS = PLAYER_DIR / "comparisons" / "v2_2_weaponless"
GENERATOR_VERSION = "2.2"
DENSITY = HD_DENSITY
# Clip of the V1.5 build -> game clip (the V1.5 publication choices).
V15_TAKES = {"hurt_a": "hurt", "fall_v15": "fall", "attack_basic_air": "attack_basic_air"}
SOCKET_KEYS = ("weapon", "hand_l", "head", "chest", "back")


def load(module: str) -> dict:
    return json.loads((RUN / module / "game_sprites_manifest.json").read_text(encoding="utf-8"))


def merged(m13: dict, m14: dict, m15: dict) -> tuple[dict, dict[str, list]]:
    """Game manifest (builder JSON format) and sockets per game clip."""
    game = G4.merged_manifest(m13, m14)
    sockets = {**m13["sockets"], **m14["sockets"]}
    for src, dst in V15_TAKES.items():
        clip = copy.deepcopy(m15["clips"][src])
        clip["source"] = f"v1_5:{src}"
        if clip["loop"]:
            clip["validation"].setdefault("stance_speed_m_s", {})
        game["clips"][dst] = clip
        game["renders"][dst] = m15["renders"][src]
        sockets[dst] = m15["sockets"][src]
    return game, sockets


def fmt(v: float) -> str:
    return G3.fmt(round(float(v), 2))


def frame_ron(f: dict) -> str:
    w, h = f["weapon"], f["hand_l"]
    return (f"(weapon: (x: {fmt(w['x'])}, y: {fmt(w['y'])}, angle: {fmt(w['angle'])}, "
            f"front: {str(w['front']).lower()}), "
            f"hand_l: (x: {fmt(h['x'])}, y: {fmt(h['y'])}, front: {str(h['front']).lower()}), "
            + ", ".join(f"{k}: (x: {fmt(f[k]['x'])}, y: {fmt(f[k]['y'])})" for k in ("head", "chest", "back"))
            + ")")


def sockets_ron(sockets: dict[str, list], order: list[str]) -> str:
    lines = ["// Equipment sockets of the player frames (V2.2), measured in Blender on the",
             "// same poses as the atlases. Generated by art-src/player/scripts/post/game_sprites_v2_2.py",
             "// and published by publish_guard.py: do not edit by hand. World units from the",
             "// sole-line pivot (x forward, y up); angle in degrees (pommel -> guard).",
             "// Runtime: src/player/visual/sockets.rs, docs/VISUAL_EQUIPMENT_V2_2.md.",
             "(", "    version: 1,", "    clips: {"]
    for key in order:
        lines.append(f'        "{key}": [' + ", ".join(frame_ron(f) for f in sockets[key]) + "],")
    lines += ["    },", ")", ""]
    return "\n".join(lines)


def weaponless_ron(text: str) -> str:
    lines = text.splitlines()
    lines[0] = "// Player sprite animations and effects (V2.2 weaponless body, finish C, model v007)."
    lines[1] = "// Generated by art-src/player/scripts/post/game_sprites_v2_2.py and published by"
    at = lines.index("    facing: Right,")
    lines.insert(at + 1, "    weapon_in_body: false,")
    return "\n".join(lines) + "\n"


def marked(sprite: Image.Image, frame: dict, pivot: tuple[float, float]) -> Image.Image:
    """The sprite with its sockets drawn (weapon line, hands, head, chest, back)."""
    out = sprite.copy()
    d = ImageDraw.Draw(out)

    def at(p: dict) -> tuple[float, float]:
        return pivot[0] + p["x"] * DENSITY, pivot[1] - p["y"] * DENSITY

    import math

    w = frame["weapon"]
    gx, gy = at(w)
    a = math.radians(w["angle"])
    d.line((gx, gy, gx + math.cos(a) * 30, gy - math.sin(a) * 30), fill=(255, 210, 60, 255), width=2)
    colours = {"weapon": (255, 210, 60), "hand_l": (90, 200, 255), "head": (255, 90, 200),
               "chest": (120, 255, 120), "back": (255, 140, 60)}
    for key, colour in colours.items():
        x, y = at(frame[key])
        d.ellipse((x - 3, y - 3, x + 3, y + 3), outline=(*colour, 255), width=2)
    return out


def comparison(game: dict, old: dict[str, Image.Image], new: dict[str, list[Image.Image]],
               sockets: dict[str, list], layout: dict, out: Path) -> Path:
    """One row per clip: published frame, candidate frame, candidate with sockets."""
    rows = []
    for group, info in layout.items():
        g = G3.GROUPS[group]
        pivot = (g["pivot_u"][0] * DENSITY, g["pivot_u"][1] * DENSITY)
        cw, ch = info["cell"]
        atlas = old[group]
        for key in g["clips"]:
            i = len(new[key]) // 2
            index = info["first"][key] + i
            col, row = index % info["columns"], index // info["columns"]
            x, y = col * (cw + G3.PADDING), row * (ch + G3.PADDING)
            published = atlas.crop((x, y, x + cw, y + ch))
            rows.append((f"{key} #{i}", [published, new[key][i], marked(new[key][i], sockets[key][i], pivot)]))
    cell_w = max(r[1][0].width for r in rows)
    cell_h = max(r[1][0].height for r in rows)
    label_w = 170
    sheet = Image.new("RGBA", (label_w + 3 * cell_w, 40 + len(rows) * cell_h), (38, 38, 46, 255))
    d = ImageDraw.Draw(sheet)
    d.text((8, 8), "V2.2 candidate: published (sabre baked) | weaponless | weaponless + sockets",
           fill=(235, 235, 235, 255), font=font(16))
    for n, (label, images) in enumerate(rows):
        y = 40 + n * cell_h
        d.text((8, y + 8), label, fill=(220, 220, 220, 255), font=font(14))
        for k, im in enumerate(images):
            sheet.alpha_composite(im, (label_w + k * cell_w, y))
    out.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stage", type=Path, default=RUN / "stage", help="staging directory")
    parser.add_argument("--sheet-dir", type=Path, default=SHEETS)
    args = parser.parse_args()
    refuse_protected_output(args.stage)
    refuse_protected_output(args.sheet_dir)
    game, sockets = merged(load("v1_3"), load("v1_4"), load("v1_5"))
    G3.GROUPS["locomotion"]["clips"] = (*G3.GROUPS["locomotion"]["clips"], *G4.NEW_LOCOMOTION)
    G3.GROUPS["combat"]["clips"] = (*G3.GROUPS["combat"]["clips"], *G4.NEW_COMBAT, *G5.NEW_COMBAT)
    sprites = {k: G3.sprites_for(game, k, "C") for k in game["clips"]}
    report = G3.validate(game, sprites)
    fails = report["failures"]
    for key, clip in game["clips"].items():
        if len(sockets.get(key, [])) != clip["frames"]:
            fails.append(f"{key}: {len(sockets.get(key, []))} socket frames for {clip['frames']} sprite frames")
    layout, order = {}, []
    args.stage.mkdir(parents=True, exist_ok=True)
    for group, g in G3.GROUPS.items():
        first, frames = {}, []
        for key in g["clips"]:
            first[key] = len(frames)
            frames += sprites[key]
            order.append(key)
        atlas = G3.pack(group, frames)
        cols = g["columns"]
        layout[group] = {"cell": (g["cell_u"][0] * DENSITY, g["cell_u"][1] * DENSITY), "columns": cols,
                         "rows": (len(frames) + cols - 1) // cols, "first": first, "size": atlas.size,
                         "frames": len(frames)}
        path = args.stage / "sprites" / "player" / f"player_{group}.png"
        path.parent.mkdir(parents=True, exist_ok=True)
        atlas.save(path)
    effects_atlas, effects_first, effects_rows = G5.pack_effects(VFX.all_frames())
    effects_path = args.stage / "sprites" / "player" / "player_effects.png"
    effects_atlas.save(effects_path)
    effects = {"first": effects_first, "rows": effects_rows, "size": effects_atlas.size}
    ron = args.stage / "animations" / "player.ron"
    ron.parent.mkdir(parents=True, exist_ok=True)
    ron.write_text(weaponless_ron(G5.ron_manifest(game, layout, effects)), encoding="utf-8")
    (args.stage / SOCKETS).write_text(sockets_ron(sockets, order), encoding="utf-8")
    (args.stage / STAGE_INFO).write_text(json.dumps(
        {"generator": Path(__file__).name, "generator_version": GENERATOR_VERSION,
         "hurt": "hurt_a", "fall": "fall_v15", "weapon_in_body": False}) + "\n", encoding="utf-8")
    old = {g: Image.open(ASSETS / "sprites" / "player" / f"player_{g}.png").convert("RGBA") for g in layout}
    sheet = comparison(game, old, sprites, sockets, layout, args.sheet_dir / "published_vs_weaponless.png")
    published_ron = (ASSETS / "animations" / "player.ron").read_text(encoding="utf-8")
    same_layout = [ln for ln in published_ron.splitlines() if ln.strip().startswith('"')] == \
        [ln for ln in ron.read_text(encoding="utf-8").splitlines() if ln.strip().startswith('"')]
    if not same_layout:
        fails.append("the candidate layout (atlases, clips, indices, durations) differs from the published one")
    effects_same = G3.sha(effects_path) == G3.sha(ASSETS / "sprites" / "player" / "player_effects.png")
    summary = {"failures": fails, "same_layout_as_published": same_layout,
               "effects_identical_to_published": effects_same, "sheet": str(sheet),
               "atlases": {g: {"size": info["size"], "frames": info["frames"]} for g, info in layout.items()},
               "staged": {"player.ron": G3.sha(ron), "player_sockets.ron": G3.sha(args.stage / SOCKETS),
                          **{g: G3.sha(args.stage / "sprites" / "player" / f"player_{g}.png")
                             for g in (*layout, "effects")}}}
    args.sheet_dir.mkdir(parents=True, exist_ok=True)
    (args.sheet_dir / "candidate_report.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"[game_sprites_v2_2] staged in {args.stage}; check with publish_guard.py check --stage {args.stage}")
    if fails:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
