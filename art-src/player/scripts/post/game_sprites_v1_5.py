"""Staging of the V1.5 game sprites and the V1.5 comparison sheets.

Reads the masters of bpy/build_game_sprites_v1_3.py, _v1_4.py and _v1_5.py
and the effect frames of vfx_v1_5.py, and writes a **staging directory**
laid out like ``assets/`` (default ``renders/v1_5_game_sprites/stage/``):

- ``sprites/player/player_locomotion.png``: the V1.4 clips; ``hurt`` and
  ``fall`` come from the variant chosen with ``--hurt`` / ``--fall``
  (``v1_4`` keeps the V1.4 clip);
- ``sprites/player/player_combat.png``: the V1.4 clips plus
  ``attack_basic_air`` (appended: no earlier index moves);
- ``sprites/player/player_effects.png``: the VFX (density 1);
- ``animations/player.ron`` and ``publish.json`` (generator 1.5).

It never writes ``assets/``: ``publish_guard.py publish --stage ...``
validates the staging and publishes it, with backup and rollback.

Experimental clips (``death_lying``, the hurt variant not chosen) are
validated and compared, never packed. Comparison sheets, GIF previews and
``game_sprites_report.json`` go to ``comparisons/v1_5_art_polish/``.

Usage:
    python3 art-src/player/scripts/post/game_sprites_v1_5.py [--hurt hurt_a|hurt_b|v1_4] [--fall fall_v15|v1_4]
        [--stage DIR] [--sheet-dir DIR]
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

from PIL import Image

import game_sprites_v1_3 as G3  # V1.3 packing, finishes and checks, unchanged
import game_sprites_v1_4 as G4  # V1.4 durations rule, unchanged
import rig_sheets as S5
import vfx_v1_5 as VFX
from contract import HD_DENSITY
from labels import font
from publish_guard import STAGE_INFO, refuse_protected_output
from resample import resize

PLAYER_DIR = Path(__file__).resolve().parents[2]
RUN_V15 = PLAYER_DIR / "renders" / "v1_5_game_sprites"
SHEETS = PLAYER_DIR / "comparisons" / "v1_5_art_polish"
GENERATOR_VERSION = "1.5"
DENSITY = HD_DENSITY
EFFECT_COLUMNS = 8
NEW_COMBAT = ("attack_basic_air",)
EXPERIMENTAL = ("death_lying",)


def merged(m13: dict, m14: dict, m15: dict, hurt: str, fall: str) -> tuple[dict, dict]:
    """(game manifest, experimental manifest) in the builder JSON format."""
    game = G4.merged_manifest(m13, m14)
    exp = {**game, "clips": {}, "renders": {}}

    def take(src: str, dst: str, into: dict) -> None:
        clip = copy.deepcopy(m15["clips"][src])
        clip["source"] = f"v1_5:{src}"
        into["clips"][dst] = clip
        into["renders"][dst] = m15["renders"][src]

    if hurt != "v1_4":
        take(hurt, "hurt", game)
    if fall != "v1_4":
        take(fall, "fall", game)
        game["clips"]["fall"]["validation"].setdefault("stance_speed_m_s", {})
    take("attack_basic_air", "attack_basic_air", game)
    for key in ("hurt_a", "hurt_b"):
        if key != hurt:
            take(key, key, exp)
    for key in EXPERIMENTAL:
        take(key, key, exp)
    for clip in exp["clips"].values():
        if clip["loop"]:
            clip["validation"].setdefault("stance_speed_m_s", {})
    return game, exp


def pack_effects(frames: dict[str, list[Image.Image]]) -> tuple[Image.Image, dict[str, int], int]:
    cw, ch = VFX.CELL
    order = [f for key in VFX.EFFECTS for f in frames[key]]
    rows = (len(order) + EFFECT_COLUMNS - 1) // EFFECT_COLUMNS
    atlas = Image.new("RGBA", (EFFECT_COLUMNS * cw + (EFFECT_COLUMNS - 1) * G3.PADDING,
                               rows * ch + (rows - 1) * G3.PADDING), (0, 0, 0, 0))
    first, n = {}, 0
    for key in VFX.EFFECTS:
        first[key] = n
        for frame in frames[key]:
            atlas.alpha_composite(frame, ((n % EFFECT_COLUMNS) * (cw + G3.PADDING),
                                          (n // EFFECT_COLUMNS) * (ch + G3.PADDING)))
            n += 1
    return atlas, first, rows


def ron_manifest(manifest: dict, layout: dict, effects: dict) -> str:
    lines = ["// Player sprite animations and effects (V1.5, finish C, model v007, x1.7 blade).",
             "// Generated by art-src/player/scripts/post/game_sprites_v1_5.py and published by",
             "// art-src/player/scripts/post/publish_guard.py: do not edit by hand.",
             "// Runtime: docs/PLAYER_VISUAL_ANIMATION_V1_3.md, docs/PLAYER_ANIMATION_EXPANSION_V1_4.md",
             "// and docs/PLAYER_ART_POLISH_V1_5.md.",
             "(", "    version: 1,", "    facing: Right,", "    atlases: {"]
    for group, info in layout.items():
        lines.append(f'        "{group}": (texture: "sprites/player/player_{group}.png", cell: ({info["cell"][0]}, '
                     f'{info["cell"][1]}), columns: {info["columns"]}, rows: {info["rows"]}, padding: {G3.PADDING}, '
                     f'density: {DENSITY}),')
    lines.append(f'        "effects": (texture: "sprites/player/player_effects.png", cell: ({VFX.CELL[0]}, '
                 f'{VFX.CELL[1]}), columns: {EFFECT_COLUMNS}, rows: {effects["rows"]}, padding: {G3.PADDING}, '
                 f'density: {VFX.DENSITY}),')
    lines += ["    },", "    clips: {"]
    for group, info in layout.items():
        g = G3.GROUPS[group]
        px, py = g["pivot_u"][0] * DENSITY, g["pivot_u"][1] * DENSITY
        for key in g["clips"]:
            clip = manifest["clips"][key]
            mode = {"Loop": f"Loop(fps: {G3.fmt(clip['fps'])})", "Once": f"Once(fps: {G3.fmt(clip['fps'])})",
                    "FitToAction": "FitToAction"}[clip["mode"]]
            fallback = "None" if key == "idle" else 'Some("idle")'
            durations = ", ".join(G3.fmt(d) for d in G4.display_durations(clip["durations_s"]))
            speed = f"Some({G3.fmt(manifest['clips']['run']['design']['reference_speed_px_s'])})" if key == "run" \
                else "None"
            lines.append(f'        "{key}": (atlas: "{group}", first: {info["first"][key]}, count: {clip["frames"]}, '
                         f'mode: {mode}, pivot: ({G3.fmt(px)}, {G3.fmt(py)}), fallback: {fallback}, '
                         f'durations: [{durations}], speed_reference: {speed}),')
    for key, effect in VFX.EFFECTS.items():
        fps = 1.0 / effect.durations[0]
        durations = ", ".join(G3.fmt(d) for d in effect.durations)
        lines.append(f'        "{key}": (atlas: "effects", first: {effects["first"][key]}, '
                     f'count: {len(effect.durations)}, mode: Once(fps: {G3.fmt(round(fps, 6))}), '
                     f'pivot: ({G3.fmt(VFX.PIVOT[0])}, {G3.fmt(VFX.PIVOT[1])}), fallback: None, '
                     f'durations: [{durations}], speed_reference: None),')
    lines += ["    },", ")", ""]
    return "\n".join(lines)


# --- comparison sheets -------------------------------------------------------------------


def tile(sprite: Image.Image, zoom: float) -> Image.Image:
    return S5.screen(sprite, "B", zoom, DENSITY)


def row_sheet(title: str, subtitle: str, rows: list[tuple[str, list[Image.Image], list[str]]], zoom: float,
              out: Path) -> Path:
    tiles = [(label, [tile(s, zoom) for s in sprites], notes) for label, sprites, notes in rows]
    width = 230 + max(sum(t.size[0] + 4 for t in ts) for _, ts, _ in tiles)
    height = 76 + sum(ts[0].size[1] + 30 for _, ts, _ in tiles)
    sheet = Image.new("RGBA", (width, height), (*S5.DARK, 255))
    draw = S5.header(sheet, title, subtitle)
    y = 70
    for label, ts, notes in tiles:
        draw.text((S5.PAD, y + 4), label, fill=S5.TEXT, font=font(14))
        for n, note in enumerate(notes):
            draw.text((S5.PAD, y + 24 + 15 * n), note, fill=S5.MUTED, font=font(11))
        x = 230
        for i, t in enumerate(ts):
            sheet.alpha_composite(t, (x, y))
            if zoom >= 2:
                draw.text((x + 3, y + 3), f"{i:02d}", fill=S5.TEXT, font=font(10))
            x += t.size[0] + 4
        y += ts[0].size[1] + 30
    sheet.convert("RGB").save(out)
    return out


def effects_sheet(frames: dict[str, list[Image.Image]], out: Path) -> Path:
    zoom = 2
    cw, ch = VFX.CELL[0] * zoom, VFX.CELL[1] * zoom
    width = 230 + 12 * (cw + 4)
    sheet = Image.new("RGBA", (width, 76 + len(frames) * (ch + 30)), (*S5.DARK, 255))
    draw = S5.header(sheet, "V1.5: efeitos visuais (atlas effects, densidade 1), ×2 sobre o fundo da sala",
                     "Célula 128×96 u, pivô (40, 95) na linha da sola, desenhados olhando para a direita. "
                     "Só apresentação: nenhum efeito tem colisão, dano ou cura.")
    y = 70
    for key, fs in frames.items():
        effect = VFX.EFFECTS[key]
        draw.text((S5.PAD, y + 4), key, fill=S5.TEXT, font=font(14))
        draw.text((S5.PAD, y + 24), f"{len(fs)} quadros, {sum(effect.durations):.2f} s", fill=S5.MUTED, font=font(11))
        x = 230
        for i, f in enumerate(fs):
            bg = Image.new("RGBA", VFX.CELL, (*S5.SCENE_BACKGROUND_FALLBACK, 255))
            bg.alpha_composite(f)
            sheet.alpha_composite(resize(bg, (cw, ch), Image.Resampling.BILINEAR), (x, y))
            draw.text((x + 3, y + 3), f"{i:02d}", fill=S5.TEXT, font=font(10))
            x += cw + 4
        y += ch + 30
    sheet.convert("RGB").save(out)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--hurt", choices=("hurt_a", "hurt_b", "v1_4"), default="hurt_a")
    parser.add_argument("--fall", choices=("fall_v15", "v1_4"), default="fall_v15")
    parser.add_argument("--run-dir", type=Path, default=RUN_V15)
    parser.add_argument("--stage", type=Path, default=RUN_V15 / "stage", help="staging directory")
    parser.add_argument("--sheet-dir", type=Path, default=SHEETS)
    args = parser.parse_args()
    refuse_protected_output(args.stage)
    m13 = json.loads((G4.RUN_V13 / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    m14 = json.loads((G4.RUN_V14 / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    m15 = json.loads((args.run_dir / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    game, exp = merged(m13, m14, m15, args.hurt, args.fall)
    G3.GROUPS["locomotion"]["clips"] = (*G3.GROUPS["locomotion"]["clips"], *G4.NEW_LOCOMOTION)
    G3.GROUPS["combat"]["clips"] = (*G3.GROUPS["combat"]["clips"], *G4.NEW_COMBAT, *NEW_COMBAT)
    sprites = {k: G3.sprites_for(game, k, "C") for k in game["clips"]}
    report = G3.validate(game, sprites)
    fails = report["failures"]
    seconds, animations = G4.game_durations()
    seconds["attack_basic_air"] = game["game_constants"]["BASIC_ATTACK_TIME"]
    for key, secs in seconds.items():
        clip = game["clips"].get(key)
        if clip is None or clip["mode"] != "FitToAction" or abs(clip["duration_s"] - secs) > 1e-6:
            fails.append(f"{key}: clip duration differs from the game ({secs} s)")
    for key, clip in game["clips"].items():
        lows = [f.get("blade_lowest_z_m") for f in clip["validation"]["frames"]]
        if lows and None not in lows and min(lows) < -0.005:
            fails.append(f"{key}: the sabre goes {min(lows)} m under the floor")
    # Layout of the character atlases (same order as V1.4, new clips appended).
    layout = {}
    args.stage.mkdir(parents=True, exist_ok=True)
    for group, g in G3.GROUPS.items():
        first, frames = {}, []
        for key in g["clips"]:
            first[key] = len(frames)
            frames += sprites[key]
        atlas = G3.pack(group, frames)
        cols = g["columns"]
        layout[group] = {"cell": (g["cell_u"][0] * DENSITY, g["cell_u"][1] * DENSITY), "columns": cols,
                         "rows": (len(frames) + cols - 1) // cols, "first": first, "size": atlas.size,
                         "frames": len(frames)}
        if max(atlas.size) > G3.MAX_SIDE:
            fails.append(f"atlas {group} is {atlas.size}, above {G3.MAX_SIDE} px")
        path = args.stage / "sprites" / "player" / f"player_{group}.png"
        path.parent.mkdir(parents=True, exist_ok=True)
        atlas.save(path)
    vfx_frames = VFX.all_frames()
    effects_atlas, effects_first, effects_rows = pack_effects(vfx_frames)
    effects_atlas.save(args.stage / "sprites" / "player" / "player_effects.png")
    layout_effects = {"first": effects_first, "rows": effects_rows, "size": effects_atlas.size}
    ron = args.stage / "animations" / "player.ron"
    ron.parent.mkdir(parents=True, exist_ok=True)
    ron.write_text(ron_manifest(game, layout, layout_effects), encoding="utf-8")
    (args.stage / STAGE_INFO).write_text(json.dumps(
        {"generator": Path(__file__).name, "generator_version": GENERATOR_VERSION,
         "hurt": args.hurt, "fall": args.fall}) + "\n", encoding="utf-8")
    # Experimental clips: validated, compared, never packed.
    G3.GROUPS["locomotion"]["clips"] = (*G3.GROUPS["locomotion"]["clips"], "hurt_a", "hurt_b")
    G3.GROUPS["combat"]["clips"] = (*G3.GROUPS["combat"]["clips"], *EXPERIMENTAL)
    exp_sprites = {k: G3.sprites_for(exp, k, "C") for k in exp["clips"]}
    exp_report = G3.validate(exp, exp_sprites)
    for key, clip in exp["clips"].items():
        low = min(f["blade_lowest_z_m"] for f in clip["validation"]["frames"])
        exp_report["clips"][key]["blade_lowest_z_m"] = low
        if low < -0.005:
            exp_report["failures"].append(f"{key}: the sabre goes {low} m under the floor")
    # Comparisons (the V1.4 clips come from the V1.4 masters, unchanged).
    sheets = args.sheet_dir
    sheets.mkdir(parents=True, exist_ok=True)
    v14 = {k: G3.sprites_for(G4.merged_manifest(m13, m14), k, "C") for k in ("hurt", "fall", "death", "attack_basic",
                                                                              "jump_rise")}
    variants = {k: G3.sprites_for({"clips": {k: m15["clips"][k]}, "renders": m15["renders"]}, k, "C")
                for k in ("hurt_a", "hurt_b", "fall_v15", "death_lying", "attack_basic_air")}
    out = {}
    for zoom, tag in ((1.0, "1x"), (3.0, "3x")):
        out[f"hurt_{tag}"] = row_sheet(
            f"Hurt: V1.4 × V1.5 A × V1.5 B (escala {tag}, 0,35 s, impacto no quadro 0)",
            "Mesma duração, mesmo stagger e mesmo recuo físico (o jogo desloca o corpo). A: recuo do tronco, "
            "braços e cabeça. B: torção do ombro da espada.",
            [("V1.4", v14["hurt"], ["9 quadros"]), ("V1.5 A", variants["hurt_a"], ["recuo + capa"]),
             ("V1.5 B", variants["hurt_b"], ["torção"])], zoom, sheets / f"hurt_compare_{tag}.png").name
        out[f"fall_{tag}"] = row_sheet(
            f"Fall: V1.4 × V1.5 (escala {tag}, loop de 4 quadros a 12 fps); jump_rise para contraste",
            "A física continua movendo o corpo; só a pose muda.",
            [("jump_rise (V1.4)", v14["jump_rise"], ["referência"]), ("fall V1.4", v14["fall"], [""]),
             ("fall V1.5", variants["fall_v15"], ["perna busca o chão,", "joelho recolhido, capa sobe"])],
            zoom, sheets / f"fall_compare_{tag}.png").name
        out[f"death_{tag}"] = row_sheet(
            f"Death: ajoelhada (V1.4, no jogo) × deitada (V1.5, experimental), escala {tag}",
            "A deitada usa a célula de combate (o corpo deitado não cabe em 64 u). Casaca posada, sem simulação.",
            [("A: ajoelhada V1.4", v14["death"], ["8 quadros, 12 fps"]),
             ("B: deitada V1.5", variants["death_lying"], ["12 quadros, 12 fps", "experimental"])],
            zoom, sheets / f"death_compare_{tag}.png").name
        out[f"attack_{tag}"] = row_sheet(
            f"Ataque básico: chão × ar (V1.5), escala {tag}, 0,28 s",
            "Mesmo tronco, braço e espada; só as pernas e a casaca mudam (pernas aéreas, sem chão invisível).",
            [("attack_basic", v14["attack_basic"], ["chão"]), ("attack_basic_air", variants["attack_basic_air"],
                                                               ["ar"])], zoom, sheets / f"attack_air_compare_{tag}.png").name
    out["effects"] = effects_sheet(vfx_frames, sheets / "vfx_v1_5.png").name
    previews = {}
    for key, sprites_k in (("hurt_a", variants["hurt_a"]), ("hurt_b", variants["hurt_b"]),
                           ("fall_v15", variants["fall_v15"]), ("death_lying", variants["death_lying"]),
                           ("attack_basic_air", variants["attack_basic_air"])):
        clip = m15["clips"][key]
        previews[key] = G3.gif(key, {"clips": {key: clip}}, sprites_k, sheets)
    report.update({"hurt": args.hurt, "fall": args.fall, "layout": layout, "effects_layout": layout_effects,
                   "game_durations_s": seconds, "skill_animations": animations, "experimental": exp_report,
                   "sheets": out, "previews": previews,
                   "staged": {"ron_sha256": G3.sha(ron),
                              **{g: G3.sha(args.stage / "sprites" / "player" / f"player_{g}.png")
                                 for g in (*layout, "effects")}}})
    (sheets / "game_sprites_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str)
                                                      + "\n", encoding="utf-8")
    for group, info in layout.items():
        print(f"[game_sprites_v1_5] {group}: {info['size']}, {info['frames']} frames")
    print(f"[game_sprites_v1_5] effects: {effects_atlas.size}, {sum(len(f) for f in vfx_frames.values())} frames")
    print(f"[game_sprites_v1_5] failures: {fails}")
    print(f"[game_sprites_v1_5] experimental failures: {exp_report['failures']}")
    print(f"[game_sprites_v1_5] staged in {args.stage}; publish with publish_guard.py")


if __name__ == "__main__":
    main()
