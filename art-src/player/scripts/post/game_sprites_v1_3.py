"""Game atlases and animation manifest of V1.3 (idle, run, dodge, attack_basic).

Reads the masters written by bpy/build_game_sprites_v1_3.py and writes what
the game loads (docs/ASSET_CONTRACT.md, sections 1, 5, 6 and 7):

- ``assets/sprites/player/player_locomotion.png``: idle, run, dodge in the
  locomotion cell (64x64 u, 128x128 texels at density 2), 8 columns, 2 px
  padding between cells, row-major;
- ``assets/sprites/player/player_combat.png``: attack_basic in the combat
  cell (128x96 u, 256x192 texels), 7 columns;
- ``assets/animations/player.ron``: atlases, clips (first, count, mode,
  pivot, fallback, per-frame durations, run speed reference).

Finish C (flat colours, the V1.3 main finish) goes to the staging directory
(``renders/v1_3_game_sprites/stage/``, laid out like ``assets/``); finish B
(the alternative) is packed the same way under
``renders/v1_3_game_sprites/atlas_B/`` for comparison only. Review sheets,
previews and ``game_sprites_report.json`` go to
``comparisons/v1_3_game_sprites/``. Deterministic for identical masters.

V1.5: this script is historical. It never writes to ``assets/`` (an output
inside it is refused) and ``publish_guard.py`` refuses its staging: generator
1.3 is older than the published pipeline and lacks the V1.4 clips.

Usage:
    python3 art-src/player/scripts/post/game_sprites_v1_3.py [--run-dir DIR] [--assets-dir STAGE] [--sheet-dir DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw

import animation_sheets_v1_2g as AS  # V1.2-G helpers (edge_touch, lowest_opaque_row, on_room), unchanged
import rig_sheets as S5
from contract import COMBAT_FRAME, COMBAT_PIVOT, FRAME, HD_DENSITY, PIVOT
from labels import font
from publish_guard import STAGE_INFO, refuse_protected_output

PLAYER_DIR = Path(__file__).resolve().parents[2]
PROJECT = PLAYER_DIR.parents[1]
RUN_DIR = PLAYER_DIR / "renders" / "v1_3_game_sprites"
ASSETS = PROJECT / "assets"
SHEETS = PLAYER_DIR / "comparisons" / "v1_3_game_sprites"
GENERATOR_VERSION = "1.3"
PADDING = 2
GROUPS = {  # contract section 6: one atlas per group, grid columns
    "locomotion": {"clips": ("idle", "run", "dodge"), "columns": 8, "cell_u": (FRAME, FRAME), "pivot_u": PIVOT},
    "combat": {"clips": ("attack_basic",), "columns": 7, "cell_u": COMBAT_FRAME, "pivot_u": COMBAT_PIVOT},
}
FALLBACK = {"idle": None, "run": "idle", "dodge": "idle", "attack_basic": "idle"}
DENSITY = HD_DENSITY  # finishes B and C: 2 texels per world unit
MAX_SIDE = 2048


def sprites_for(manifest: dict, key: str, finish: str) -> list[Image.Image]:
    clip = manifest["clips"][key]
    combat = clip["group"] == "combat"
    source = "W_flat" if finish == "C" else "W_shaded"
    return [S5.finishes(Path(manifest["renders"][key]["masters"][str(i)][source]), combat)["B"]
            for i in range(clip["frames"])]


def pack(group: str, frames: list[Image.Image]) -> Image.Image:
    g = GROUPS[group]
    cw, ch = g["cell_u"][0] * DENSITY, g["cell_u"][1] * DENSITY
    cols = g["columns"]
    rows = (len(frames) + cols - 1) // cols
    atlas = Image.new("RGBA", (cols * cw + (cols - 1) * PADDING, rows * ch + (rows - 1) * PADDING), (0, 0, 0, 0))
    for i, frame in enumerate(frames):
        if frame.size != (cw, ch):
            raise ValueError(f"{group} frame {i} is {frame.size}, cell {(cw, ch)}")
        atlas.alpha_composite(frame, ((i % cols) * (cw + PADDING), (i // cols) * (ch + PADDING)))
    return atlas


def fmt(v: float) -> str:
    """Float literal for RON: at most 6 decimals, always with a decimal point."""
    text = f"{v:.6f}".rstrip("0")
    return text + "0" if text.endswith(".") else text


def ron_manifest(manifest: dict, layout: dict) -> str:
    lines = ["// Player sprite animations (V1.3, finish C, model v007, x1.7 blade).",
             "// Generated by art-src/player/scripts/post/game_sprites_v1_3.py: do not edit by hand.",
             "// Contract: docs/ASSET_CONTRACT.md (sections 5-7); runtime: docs/PLAYER_VISUAL_ANIMATION_V1_3.md.",
             "(", "    version: 1,", "    facing: Right,", "    atlases: {"]
    for group, info in layout.items():
        lines.append(f'        "{group}": (texture: "sprites/player/player_{group}.png", cell: ({info["cell"][0]}, '
                     f'{info["cell"][1]}), columns: {info["columns"]}, rows: {info["rows"]}, padding: {PADDING}, '
                     f'density: {DENSITY}),')
    lines += ["    },", "    clips: {"]
    for group, info in layout.items():
        g = GROUPS[group]
        px, py = g["pivot_u"][0] * DENSITY, g["pivot_u"][1] * DENSITY
        for key in g["clips"]:
            clip = manifest["clips"][key]
            first = info["first"][key]
            mode = f"Loop(fps: {fmt(clip['fps'])})" if clip["loop"] else "FitToAction"
            fallback = "None" if FALLBACK[key] is None else f'Some("{FALLBACK[key]}")'
            durations = ", ".join(fmt(d) for d in clip["durations_s"])
            speed = f"Some({fmt(manifest['clips']['run']['design']['reference_speed_px_s'])})" if key == "run" \
                else "None"
            lines.append(f'        "{key}": (atlas: "{group}", first: {first}, count: {clip["frames"]}, mode: {mode}, '
                         f'pivot: ({fmt(px)}, {fmt(py)}), fallback: {fallback}, durations: [{durations}], '
                         f'speed_reference: {speed}),')
    lines += ["    },", ")", ""]
    return "\n".join(lines)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def contact_sheet(manifest: dict, sprites: dict[str, list[Image.Image]], out: Path) -> Path:
    zoom = 2.0
    rows = []
    for key in ("idle", "run", "dodge", "attack_basic"):
        tiles = [S5.screen(s, "B", zoom, DENSITY) for s in sprites[key]]
        rows.append((key, tiles))
    width = 200 + max(sum(t.size[0] + 4 for t in tiles) for _, tiles in rows)
    height = 76 + sum(tiles[0].size[1] + 40 for _, tiles in rows)
    sheet = Image.new("RGBA", (width, height), (*S5.DARK, 255))
    draw = S5.header(sheet, "V1.3: sprites do jogo (acabamento C, lâmina ×1,7), ×2 sobre o fundo da sala",
                     "Exatamente o que vai em assets/sprites/player/. Célula de movimento 64×64 u, de combate "
                     "128×96 u, densidade 2. t = início do quadro.")
    y = 70
    for key, tiles in rows:
        clip = manifest["clips"][key]
        mode = f"loop {clip['fps']} fps" if clip["loop"] else f"FitToAction {clip['duration_s']:.3f} s"
        draw.text((S5.PAD, y + 8), key, fill=S5.TEXT, font=font(15))
        draw.text((S5.PAD, y + 30), f"{clip['frames']} quadros, {mode}", fill=S5.MUTED, font=font(11))
        x = 200
        for i, tile in enumerate(tiles):
            sheet.alpha_composite(tile, (x, y))
            draw.text((x + 3, y + 3), f"{i:02d} {clip['times_s'][i]:.3f}s", fill=S5.TEXT, font=font(10))
            x += tile.size[0] + 4
        y += tiles[0].size[1] + 40
    path = out / "game_sprites_contact_sheet.png"
    sheet.convert("RGB").save(path)
    return path


def run_sheet(manifest: dict, sprites: list[Image.Image], out: Path) -> Path:
    """Run at 24 fps and the 12 fps alternative, with the stance-foot speed against the game speed."""
    clip = manifest["clips"]["run"]
    design = clip["design"]
    zoom = 2.0
    tiles = [S5.screen(s, "B", zoom, DENSITY) for s in sprites]
    tw, th = tiles[0].size
    sheet = Image.new("RGBA", (200 + len(tiles) * (tw + 4), 96 + 2 * (th + 40) + 70), (*S5.DARK, 255))
    speeds = clip["validation"]["stance_speed_m_s"]
    flat = [abs(v) for side in speeds.values() for v in side]
    mean = sum(flat) / len(flat) if flat else 0.0
    draw = S5.header(sheet, f"Run: ciclo para {design['reference_speed_px_s']:.0f} px/s "
                     f"({design['reference_speed_m_s']:.2f} m/s), {clip['frames']} quadros a 24 fps "
                     f"= {clip['duration_s']:.3f} s",
                     f"Apoio = {design['stance_share'] * 100:.1f} % do ciclo, {design['stance_travel_m']:.2f} m de "
                     f"passada no apoio; o corpo avança {design['body_travel_per_cycle_px']:.1f} px por ciclo. "
                     f"Pé de apoio medido: {mean:.2f} m/s ({(mean / design['reference_speed_m_s'] - 1) * 100:+.1f} %).")
    for r, (label, picked) in enumerate((("24 fps", range(clip["frames"])), ("12 fps", range(0, clip["frames"], 2)))):
        y = 70 + r * (th + 40)
        draw.text((S5.PAD, y + th // 2 - 8), label, fill=S5.TEXT, font=font(15))
        for i in picked:
            x = 200 + i * (tw + 4)  # same time axis: a 12 fps frame spans two 24 fps slots
            sheet.alpha_composite(tiles[i], (x, y))
            draw.text((x + 3, y + 3), f"{i:02d}", fill=S5.TEXT, font=font(10))
    path = out / "run_cycle_v1_3.png"
    sheet.convert("RGB").save(path)
    return path


def gif(key: str, manifest: dict, sprites: list[Image.Image], out: Path) -> dict[str, object]:
    clip = manifest["clips"][key]
    frames = [S5.screen(s, "B", 3.0, DENSITY).convert("RGB") for s in sprites]
    delays, carried = [], 0.0
    for d in clip["durations_s"]:
        exact = d * 1000.0 + carried
        ms = max(10, int(round(exact / 10.0)) * 10)
        carried = exact - ms
        delays.append(ms)
    path = out / "previews" / f"{key}_C.gif"
    path.parent.mkdir(parents=True, exist_ok=True)
    frames[0].save(path, save_all=True, append_images=frames[1:], duration=delays, loop=0, disposal=1)
    return {"file": path.name, "delays_ms": delays}


def validate(manifest: dict, sprites: dict[str, list[Image.Image]]) -> dict[str, object]:
    report: dict[str, object] = {"clips": {}, "failures": []}
    fails: list[str] = report["failures"]  # type: ignore[assignment]
    for key, clip in manifest["clips"].items():
        g = next(n for n, info in GROUPS.items() if key in info["clips"])
        cw, ch = GROUPS[g]["cell_u"][0] * DENSITY, GROUPS[g]["cell_u"][1] * DENSITY
        pivot_y = GROUPS[g]["pivot_u"][1] * DENSITY
        frames = clip["validation"]["frames"]
        touches = {}
        for i, masters in manifest["renders"][key]["masters"].items():
            for variant, path in masters.items():
                t = AS.edge_touch(Path(path))
                if any(t.values()):
                    touches[f"{i}:{variant}"] = t
        lows = [AS.lowest_opaque_row(s) for s in sprites[key]]
        hashes = [hashlib.sha256(s.tobytes()).hexdigest() for s in sprites[key]]
        dups = [i for i in range(1, len(hashes)) if hashes[i] == hashes[i - 1]]
        if clip["loop"] and hashes[0] == hashes[-1]:
            dups.append(0)
        entry = {
            "frames": clip["frames"], "duration_s": clip["duration_s"],
            "worst_severity": min((f["max_severity"] for f in frames), key=AS.SEVERITY_ORDER.index),
            "max_sword_drift_m": max(f["sword_offset_drift_m"] for f in frames),
            "max_shell_residual_m": max(f["shell_residual_m"] for f in frames),
            "lowest_z_range_m": [min(f["lowest_z_m"] for f in frames), max(f["lowest_z_m"] for f in frames)],
            "pops": {f["index"]: f["step_from_previous"]["pops"] for f in frames[1:] if f["step_from_previous"]["pops"]},
            "edge_touches": touches, "lowest_opaque_row": [min(lows), max(lows)], "pivot_y": pivot_y,
            "duplicates": dups, "sizes": sorted({s.size for s in sprites[key]}),
        }
        if clip["loop"]:
            entry["loop_closure_max_m"] = clip["validation"]["loop_closure_max_m"]
            entry["stance_speed_m_s"] = clip["validation"]["stance_speed_m_s"]
        report["clips"][key] = entry
        if entry["worst_severity"] in ("Crítico", "Alto", "Médio"):
            fails.append(f"{key}: {entry['worst_severity']}")
        if touches:
            fails.append(f"{key}: figure reaches the cell edge {sorted(touches)} (would be cut)")
        if entry["sizes"] != [(cw, ch)]:
            fails.append(f"{key}: sprite sizes {entry['sizes']}")
        # The sole sits on the pivot line, except in the run's flight frames, where
        # the lowest boot is ``lowest_z_m`` above the floor (measured in Blender).
        m_per_px = manifest["contract"]["metres_per_px"]
        expected = [pivot_y - f["lowest_z_m"] / m_per_px * DENSITY for f in frames]
        off = [round(low - exp, 2) for low, exp in zip(lows, expected)]
        entry["sole_row_minus_expected"] = [min(off), max(off)]
        # Grounded frames: the sole is on the pivot line (the soft rim may add a row).
        # Flight frames: something (coat hem, blade) may hang below the boots, but
        # nothing may go under the floor.
        bad = [i for i, (low, f, o) in enumerate(zip(lows, frames, off))
               if low > pivot_y + 1.5 or (f["lowest_z_m"] < 0.005 and not -4 <= o <= 1.5)]
        if bad:
            fails.append(f"{key}: frames {bad}: lowest opaque rows {lows}, expected {expected}")
        if dups:
            fails.append(f"{key}: duplicated consecutive frames {dups}")
        if entry["max_sword_drift_m"] > 1e-5 or entry["max_shell_residual_m"] > 1e-4 or entry["pops"]:
            fails.append(f"{key}: rig/shell check failed")
        if key in ("attack_basic", "dodge"):
            target = manifest["game_constants"]["BASIC_ATTACK_TIME" if key == "attack_basic" else "PLAYER_DODGE_TIME"]
            if abs(clip["duration_s"] - target) > 1e-6:
                fails.append(f"{key}: {clip['duration_s']} s, game {target} s")
        if clip["loop"] and clip["validation"]["loop_closure_max_m"] > 1e-4:
            fails.append(f"{key}: loop does not close")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-dir", type=Path, default=RUN_DIR)
    parser.add_argument("--assets-dir", type=Path, default=RUN_DIR / "stage", help="staging directory")
    parser.add_argument("--sheet-dir", type=Path, default=SHEETS)
    args = parser.parse_args()
    refuse_protected_output(args.assets_dir)
    manifest = json.loads((args.run_dir / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    sprites = {f: {k: sprites_for(manifest, k, f) for k in manifest["clips"]} for f in ("C", "B")}
    report = validate(manifest, sprites["C"])
    layout = {}
    written = {}
    for group, g in GROUPS.items():
        first, frames = {}, []
        for key in g["clips"]:
            first[key] = len(frames)
            frames += sprites["C"][key]
        atlas_c = pack(group, frames)
        atlas_b = pack(group, [s for key in g["clips"] for s in sprites["B"][key]])
        cols = g["columns"]
        layout[group] = {"cell": (g["cell_u"][0] * DENSITY, g["cell_u"][1] * DENSITY), "columns": cols,
                         "rows": (len(frames) + cols - 1) // cols, "first": first, "size": atlas_c.size}
        if max(atlas_c.size) > MAX_SIDE:
            report["failures"].append(f"atlas {group} is {atlas_c.size}, above {MAX_SIDE} px")
        path_c = args.assets_dir / "sprites" / "player" / f"player_{group}.png"
        path_b = args.run_dir / "atlas_B" / f"player_{group}.png"
        for path, atlas in ((path_c, atlas_c), (path_b, atlas_b)):
            path.parent.mkdir(parents=True, exist_ok=True)
            atlas.save(path)
        written[group] = {"C": {"file": f"sprites/player/{path_c.name}", "size": atlas_c.size, "sha256": sha(path_c),
                                "bytes_rgba": atlas_c.size[0] * atlas_c.size[1] * 4},
                          "B": {"size": atlas_b.size, "sha256": sha(path_b)}}
    ron_path = args.assets_dir / "animations" / "player.ron"
    ron_path.parent.mkdir(parents=True, exist_ok=True)
    ron_path.write_text(ron_manifest(manifest, layout), encoding="utf-8")
    (args.assets_dir / STAGE_INFO).write_text(json.dumps(
        {"generator": Path(__file__).name, "generator_version": GENERATOR_VERSION}) + "\n", encoding="utf-8")
    args.sheet_dir.mkdir(parents=True, exist_ok=True)
    sheets = {"contact": contact_sheet(manifest, sprites["C"], args.sheet_dir).name,
              "run": run_sheet(manifest, sprites["C"]["run"], args.sheet_dir).name}
    previews = {k: gif(k, manifest, sprites["C"][k], args.sheet_dir) for k in manifest["clips"]}
    report.update({"atlases": written, "layout": {g: {k: v for k, v in i.items()} for g, i in layout.items()},
                   "manifest_ron_sha256": sha(ron_path), "sheets": sheets, "previews": previews,
                   "run_design": manifest["clips"]["run"]["design"]})
    (args.sheet_dir / "game_sprites_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False,
                                                                       default=str) + "\n", encoding="utf-8")
    for group, info in written.items():
        print(f"[game_sprites] {group}: {info['C']['size']} -> {info['C']['file']}")
    print(f"[game_sprites] failures: {report['failures']}")


if __name__ == "__main__":
    main()
