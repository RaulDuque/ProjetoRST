"""Game atlases and manifest of V1.4: the V1.3 clips plus the expansion clips.

Reads the masters of bpy/build_game_sprites_v1_3.py (idle, run, dodge,
attack_basic) and bpy/build_game_sprites_v1_4.py (hurt, death, jump_rise,
fall, land, crouch, guard_start, slash_crescent, slash_rising,
cast_forward, cast_up) and writes to a staging directory laid out like
``assets/`` (default ``renders/v1_4_game_sprites/stage/``; V1.5: never
``assets/`` itself, which only ``publish_guard.py`` writes):

- ``assets/sprites/player/player_locomotion.png`` (locomotion cell, 8 columns);
- ``assets/sprites/player/player_combat.png`` (combat cell, 7 columns);
- ``assets/animations/player.ron`` (same format as V1.3, plus ``Once`` clips).

The V1.3 clips keep their first index in each atlas (they come first, in
the same order). Durations are checked against the game (read-only):
``PLAYER_HURT_TIME`` in src/core/constants.rs and the ``execution_time`` of
each skill/spell RON, whose ``animation`` key must name a clip. Finish C goes
to the staging directory; finish B is packed under ``renders/v1_4_game_sprites/atlas_B/``.
Review sheet, previews and ``game_sprites_report.json`` go to
``comparisons/v1_4_game_sprites/``. Deterministic for identical masters.

Usage:
    python3 art-src/player/scripts/post/game_sprites_v1_4.py [--run-dir DIR] [--assets-dir STAGE] [--sheet-dir DIR]

V1.5: historical. ``publish_guard.py`` refuses its staging once a newer
pipeline is published (generator 1.4 is older than the lock).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from PIL import Image

import game_sprites_v1_3 as G3  # V1.3 packing, finishes and checks, unchanged
import rig_sheets as S5
from contract import HD_DENSITY
from labels import font
from publish_guard import STAGE_INFO, refuse_protected_output

PLAYER_DIR = Path(__file__).resolve().parents[2]
PROJECT = PLAYER_DIR.parents[1]
RUN_V13 = PLAYER_DIR / "renders" / "v1_3_game_sprites"
RUN_V14 = PLAYER_DIR / "renders" / "v1_4_game_sprites"
SHEETS = PLAYER_DIR / "comparisons" / "v1_4_game_sprites"
DENSITY = HD_DENSITY
GENERATOR_VERSION = "1.4"
NEW_LOCOMOTION = ("hurt", "death", "jump_rise", "fall", "land", "crouch", "guard_start")
NEW_COMBAT = ("slash_crescent", "slash_rising", "cast_forward", "cast_up")
FALLBACK = {"idle": None}  # every other clip falls back to idle
SKILL_FILES = ("assets/data/skills/sword_techniques.ron", "assets/data/spells/elemental.ron")


def game_durations() -> tuple[dict[str, float], dict[str, str]]:
    """Gameplay seconds per action clip and skill id -> animation key (read-only)."""
    constants = (PROJECT / "src" / "core" / "constants.rs").read_text(encoding="utf-8")
    hurt = float(re.search(r"pub const PLAYER_HURT_TIME: f32 = ([0-9.]+);", constants).group(1))
    seconds = {"hurt": hurt}
    animations = {}
    for name in SKILL_FILES:
        text = (PROJECT / name).read_text(encoding="utf-8")
        for block in re.split(r"\n\s*\(\n", text):
            sid = re.search(r'id: "([a-z_]+)"', block)
            anim = re.search(r'animation: "([a-z_]+)"', block)
            exe = re.search(r"execution_time: ([0-9.]+)", block)
            if sid and anim and exe:
                animations[sid.group(1)] = anim.group(1)
                seconds[anim.group(1)] = float(exe.group(1))
    return seconds, animations


def merged_manifest(m13: dict, m14: dict) -> dict:
    clips = {}
    for key, clip in m13["clips"].items():
        clips[key] = {**clip, "mode": "Loop" if clip["loop"] else "FitToAction"}
    clips.update(m14["clips"])
    for clip in clips.values():  # a loop without ground contact (fall) has no stance speed
        if clip["loop"]:
            clip["validation"].setdefault("stance_speed_m_s", {})
    renders = {**m13["renders"], **m14["renders"]}
    return {**m14, "clips": clips, "renders": renders}


MIN_DISPLAY_S = 0.025  # 1.5 frames at 60 Hz: shorter frames may never be shown


def display_durations(durations: list[float]) -> list[float]:
    """Frame durations for the game: the exact clip length is kept, but a last
    frame shorter than MIN_DISPLAY_S (e.g. 0.30 s = 7 x 1/24 + 0.0083 s) would be
    skipped at 60 Hz, so the last two frames share their time equally."""
    out = list(durations)
    if len(out) >= 2 and out[-1] < MIN_DISPLAY_S:
        shared = (out[-2] + out[-1]) / 2.0
        out[-2] = out[-1] = shared
    return out


def ron_manifest(manifest: dict, layout: dict) -> str:
    lines = ["// Player sprite animations (V1.4, finish C, model v007, x1.7 blade).",
             "// Generated by art-src/player/scripts/post/game_sprites_v1_4.py: do not edit by hand.",
             "// Contract: docs/ASSET_CONTRACT.md (sections 5-7); runtime: docs/PLAYER_VISUAL_ANIMATION_V1_3.md",
             "// and docs/PLAYER_ANIMATION_EXPANSION_V1_4.md.",
             "(", "    version: 1,", "    facing: Right,", "    atlases: {"]
    for group, info in layout.items():
        lines.append(f'        "{group}": (texture: "sprites/player/player_{group}.png", cell: ({info["cell"][0]}, '
                     f'{info["cell"][1]}), columns: {info["columns"]}, rows: {info["rows"]}, padding: {G3.PADDING}, '
                     f'density: {DENSITY}),')
    lines += ["    },", "    clips: {"]
    for group, info in layout.items():
        g = G3.GROUPS[group]
        px, py = g["pivot_u"][0] * DENSITY, g["pivot_u"][1] * DENSITY
        for key in g["clips"]:
            clip = manifest["clips"][key]
            mode = {"Loop": f"Loop(fps: {G3.fmt(clip['fps'])})", "Once": f"Once(fps: {G3.fmt(clip['fps'])})",
                    "FitToAction": "FitToAction"}[clip["mode"]]
            fallback = "None" if FALLBACK.get(key, "idle") is None else 'Some("idle")'
            durations = ", ".join(G3.fmt(d) for d in display_durations(clip["durations_s"]))
            speed = f"Some({G3.fmt(manifest['clips']['run']['design']['reference_speed_px_s'])})" if key == "run" \
                else "None"
            lines.append(f'        "{key}": (atlas: "{group}", first: {info["first"][key]}, count: {clip["frames"]}, '
                         f'mode: {mode}, pivot: ({G3.fmt(px)}, {G3.fmt(py)}), fallback: {fallback}, '
                         f'durations: [{durations}], speed_reference: {speed}),')
    lines += ["    },", ")", ""]
    return "\n".join(lines)


def contact_sheet(manifest: dict, sprites: dict, keys: tuple[str, ...], out: Path) -> Path:
    zoom = 2.0
    rows = [(k, [S5.screen(s, "B", zoom, DENSITY) for s in sprites[k]]) for k in keys]
    width = 200 + max(sum(t.size[0] + 4 for t in tiles) for _, tiles in rows)
    height = 76 + sum(tiles[0].size[1] + 40 for _, tiles in rows)
    sheet = Image.new("RGBA", (width, height), (*S5.DARK, 255))
    draw = S5.header(sheet, "V1.4: novas animações do jogo (acabamento C, lâmina ×1,7), ×2 sobre o fundo da sala",
                     "Exatamente o que vai em assets/sprites/player/. Locomoção 64×64 u, combate 128×96 u, "
                     "densidade 2. t = início do quadro.")
    y = 70
    for key, tiles in rows:
        clip = manifest["clips"][key]
        mode = {"Loop": f"loop {clip['fps']} fps", "Once": f"uma vez, {clip['fps']} fps, segura o último",
                "FitToAction": f"ação {clip['duration_s']:.3f} s"}[clip["mode"]]
        draw.text((S5.PAD, y + 8), key, fill=S5.TEXT, font=font(15))
        draw.text((S5.PAD, y + 30), f"{clip['frames']} quadros", fill=S5.MUTED, font=font(11))
        draw.text((S5.PAD, y + 46), mode, fill=S5.MUTED, font=font(11))
        x = 200
        for i, tile in enumerate(tiles):
            sheet.alpha_composite(tile, (x, y))
            draw.text((x + 3, y + 3), f"{i:02d} {clip['times_s'][i]:.3f}s", fill=S5.TEXT, font=font(10))
            x += tile.size[0] + 4
        y += tiles[0].size[1] + 40
    path = out / "game_sprites_v1_4_contact_sheet.png"
    sheet.convert("RGB").save(path)
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-dir", type=Path, default=RUN_V14)
    parser.add_argument("--run-dir-v13", type=Path, default=RUN_V13)
    parser.add_argument("--assets-dir", type=Path, default=RUN_V14 / "stage", help="staging directory")
    parser.add_argument("--sheet-dir", type=Path, default=SHEETS)
    args = parser.parse_args()
    refuse_protected_output(args.assets_dir)
    m13 = json.loads((args.run_dir_v13 / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    m14 = json.loads((args.run_dir / "game_sprites_manifest.json").read_text(encoding="utf-8"))
    manifest = merged_manifest(m13, m14)
    # Extend the V1.3 groups (same order, new clips appended: V1.3 indices do not move).
    G3.GROUPS["locomotion"]["clips"] = (*G3.GROUPS["locomotion"]["clips"], *NEW_LOCOMOTION)
    G3.GROUPS["combat"]["clips"] = (*G3.GROUPS["combat"]["clips"], *NEW_COMBAT)
    sprites = {f: {k: G3.sprites_for(manifest, k, f) for k in manifest["clips"]} for f in ("C", "B")}
    report = G3.validate(manifest, sprites["C"])
    fails = report["failures"]
    seconds, animations = game_durations()
    report["game_durations_s"] = seconds
    report["skill_animations"] = animations
    for skill, clip in animations.items():
        if clip not in manifest["clips"]:
            fails.append(f"skill {skill}: animation {clip!r} has no clip")
    for key, secs in seconds.items():
        clip = manifest["clips"].get(key)
        if clip is None or clip["mode"] != "FitToAction" or abs(clip["duration_s"] - secs) > 1e-6:
            fails.append(f"{key}: clip duration differs from the game ({secs} s)")
    for key in (*NEW_LOCOMOTION, *NEW_COMBAT):
        low = min(f["blade_lowest_z_m"] for f in manifest["clips"][key]["validation"]["frames"])
        report["clips"][key]["blade_lowest_z_m"] = low
        if low < -0.005:
            fails.append(f"{key}: the sabre goes {low} m under the floor")
    layout, written = {}, {}
    for group, g in G3.GROUPS.items():
        first, frames, frames_b = {}, [], []
        for key in g["clips"]:
            first[key] = len(frames)
            frames += sprites["C"][key]
            frames_b += sprites["B"][key]
        atlas_c, atlas_b = G3.pack(group, frames), G3.pack(group, frames_b)
        cols = g["columns"]
        layout[group] = {"cell": (g["cell_u"][0] * DENSITY, g["cell_u"][1] * DENSITY), "columns": cols,
                         "rows": (len(frames) + cols - 1) // cols, "first": first, "size": atlas_c.size,
                         "frames": len(frames)}
        if max(atlas_c.size) > G3.MAX_SIDE:
            fails.append(f"atlas {group} is {atlas_c.size}, above {G3.MAX_SIDE} px")
        path_c = args.assets_dir / "sprites" / "player" / f"player_{group}.png"
        path_b = args.run_dir / "atlas_B" / f"player_{group}.png"
        for path, atlas in ((path_c, atlas_c), (path_b, atlas_b)):
            path.parent.mkdir(parents=True, exist_ok=True)
            atlas.save(path)
        written[group] = {"C": {"file": f"sprites/player/{path_c.name}", "size": atlas_c.size,
                                "sha256": G3.sha(path_c), "bytes_rgba": atlas_c.size[0] * atlas_c.size[1] * 4},
                          "B": {"size": atlas_b.size, "sha256": G3.sha(path_b)}}
    ron_path = args.assets_dir / "animations" / "player.ron"
    ron_path.parent.mkdir(parents=True, exist_ok=True)
    ron_path.write_text(ron_manifest(manifest, layout), encoding="utf-8")
    (args.assets_dir / STAGE_INFO).write_text(json.dumps(
        {"generator": Path(__file__).name, "generator_version": GENERATOR_VERSION}) + "\n", encoding="utf-8")
    args.sheet_dir.mkdir(parents=True, exist_ok=True)
    sheet = contact_sheet(manifest, sprites["C"], (*NEW_LOCOMOTION, *NEW_COMBAT), args.sheet_dir)
    previews = {k: G3.gif(k, manifest, sprites["C"][k], args.sheet_dir) for k in (*NEW_LOCOMOTION, *NEW_COMBAT)}
    report.update({"atlases": written, "layout": layout, "manifest_ron_sha256": G3.sha(ron_path),
                   "sheets": {"contact": sheet.name}, "previews": previews})
    (args.sheet_dir / "game_sprites_report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8")
    for group, info in written.items():
        print(f"[game_sprites_v1_4] {group}: {info['C']['size']}, {layout[group]['frames']} frames")
    print(f"[game_sprites_v1_4] failures: {fails}")


if __name__ == "__main__":
    main()
